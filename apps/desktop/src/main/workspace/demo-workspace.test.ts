/** A real-disk folder-backed WorkspaceService plus the services the demo needs. */
function makeServices() {
  const createBackend = (bytes?: Uint8Array) => InProcessDbBackend.open(bytes);
  const ws = new WorkspaceService({
    createBackend,
    crypto: new CryptoService(),
    fs: { read: () => Promise.resolve(null), write: () => Promise.resolve() },
    deviceId: () => DEVICE,
    now: () => new Date(NOW),
    folder: new FolderPersistence({ createBackend, deviceId: () => DEVICE, now: () => NOW }),
    probePath: async (path) => {
      try {
        return (await stat(path)).isDirectory() ? 'folder' : 'file';
      } catch {
        return 'missing';
      }
    },
  });
  const org = new OrganizationService(ws);
  const changelog = new ChangelogService(ws, () => null);
  const templates = new TemplateService(ws, org, changelog);
  const releases = new ReleaseService(ws, templates, changelog);
  const environments = new EnvironmentService(ws, () => null);
  const templateData = new TemplateDataProvider(ws, releases);
  const host = new SeeboHost({}, { templateData, envData: environments });
  const render = new RenderService(ws, templates, host, releases);
  const apiRequest = new ApiRequestService(templates, host, org);
  return { ws, org, templates, releases, environments, render, apiRequest };
}

async function generate(dir: string): Promise<void> {
  rmSync(dir, { recursive: true, force: true });
  const { ws, org, templates, releases, environments } = makeServices();
  await ws.create({ name: 'Swaft demo', location: dir, encrypt: false });

  await org.createProject({
    id: ID.project,
    name: 'Getting started',
    color: '#4f7cff',
    description: 'A tour of Swaft: documents, HTTP requests, code and a scenario.',
  });
  for (const [id, name] of [
    [ID.documents, 'Documents'],
    [ID.http, 'HTTP'],
    [ID.code, 'Code'],
    [ID.scenarios, 'Scenarios'],
  ] as const) {
    await org.createFolder({ id, name, projectId: ID.project });
  }

  await templates.createTemplate({
    id: ID.welcome,
    folderId: ID.documents,
    name: 'Welcome letter',
    type: 'document',
    subtype: 'markdown',
    source: WELCOME_SOURCE,
  });
  await templates.createTemplate({
    id: ID.company,
    folderId: ID.documents,
    name: 'company',
    type: 'document',
    subtype: 'json',
    source: COMPANY_SOURCE,
  });
  await templates.createTemplate({
    id: ID.getEcho,
    folderId: ID.http,
    name: 'Get echo',
    type: 'api',
    subtype: 'json',
    source: JSON.stringify(GET_ECHO, null, 2),
  });
  await templates.createTemplate({
    id: ID.postEcho,
    folderId: ID.http,
    name: 'Post echo',
    type: 'api',
    subtype: 'json',
    source: JSON.stringify(POST_ECHO, null, 2),
  });
  await templates.createTemplate({
    id: ID.greeting,
    folderId: ID.code,
    name: 'greeting',
    type: 'capability',
    source: GREETING_SOURCE,
  });
  await templates.createTemplate({
    id: ID.echoFlow,
    folderId: ID.scenarios,
    name: 'Echo flow',
    type: 'scenario',
    source: serializeScenarioGraph(ECHO_FLOW),
  });

  for (const id of [ID.welcome, ID.getEcho, ID.echoFlow]) await org.addTemplateTag(id, 'demo');
  await releases.createRelease(ID.welcome, 'v1');

  const env = await environments.create({
    name: 'Public echo',
    description: 'Public echo service used by the HTTP demo requests.',
    ownerKind: 'workspace',
  });
  await environments.update(env.id, { vars: { BASE_URL: 'https://httpbin.org' } });
  // The active selection is local-only (`.swaft/`, git-ignored): it only helps this machine.
  await environments.setSelection(env.id);

  await ws.save();
  await ws.close();
  // Local caches (history, input state, selection) are not part of the shareable demo.
  rmSync(join(dir, '.swaft'), { recursive: true, force: true });
}

describe.runIf(process.env.SWAFT_WRITE_DEMO === '1')('demo workspace generator', () => {
  it('writes examples/demo-workspace', async () => {
    await generate(DEMO_DIR);
    expect(existsSync(join(DEMO_DIR, 'workspace.json'))).toBe(true);
  }, 120_000);
});

describe('demo workspace (examples/demo-workspace)', { timeout: 30_000 }, () => {
  async function openCopy() {
    const dir = join(mkdtempSync(join(tmpdir(), 'swaft-demo-')), 'demo-workspace');
    cpSync(DEMO_DIR, dir, { recursive: true });
    const svc = makeServices();
    const opened = await svc.ws.open({ path: dir });
    return { ...svc, opened };
  }

  it('opens with the expected project, folders, templates and environment', async () => {
    const { opened, org, environments, releases, ws } = await openCopy();
    expect(opened.name).toBe('Swaft demo');
    expect(opened.storageMode).toBe('local');

    const tree = await org.getTree();
    expect(tree.projects.map((p) => p.name)).toEqual(['Getting started']);
    expect(tree.folders.map((f) => f.name).sort()).toEqual([
      'Code',
      'Documents',
      'HTTP',
      'Scenarios',
    ]);
    const byName = new Map(tree.templates.map((t) => [t.name, t]));
    expect([...byName.keys()].sort()).toEqual(
      ['company', 'Echo flow', 'Get echo', 'greeting', 'Post echo', 'Welcome letter'].sort(),
    );
    expect(byName.get('Welcome letter')).toMatchObject({ type: 'document', subtype: 'markdown' });
    expect(byName.get('company')).toMatchObject({ type: 'document', subtype: 'json' });
    expect(byName.get('Get echo')).toMatchObject({ type: 'api', method: 'GET' });
    expect(byName.get('Post echo')).toMatchObject({ type: 'api', method: 'POST' });
    expect(byName.get('greeting')).toMatchObject({ type: 'capability' });
    expect(byName.get('Echo flow')).toMatchObject({ type: 'scenario' });
    expect(tree.tags.map((t) => t.name)).toEqual(['demo']);
    expect((await releases.listReleases(ID.welcome)).map((r) => r.name)).toEqual(['v1']);

    const envs = await environments.list();
    expect(envs.map((e) => e.name)).toEqual(['Public echo']);
    expect((await environments.get(envs[0]!.id)).vars).toEqual({ BASE_URL: 'https://httpbin.org' });
    await ws.close();
  });

  it('keeps the Echo flow scenario graph intact', async () => {
    const { templates, ws } = await openCopy();
    const tpl = await templates.requireTemplate(ID.echoFlow);
    const { graph, ok } = parseScenarioGraph(tpl.source);
    expect(ok).toBe(true);
    expect(graph.nodes.map((n) => n.id).sort()).toEqual([
      'get',
      'letter',
      'ok',
      'post',
      'start',
      'wait',
    ]);
    expect(graph.nodes.find((n) => n.id === 'ok')?.condition).toBe(
      "${ previous('echo').status == 200 }",
    );
    expect(graph.nodes.find((n) => n.id === 'letter')).toMatchObject({
      ref: ID.welcome,
      templateType: 'document',
    });
    expect(graph.edges).toHaveLength(5);
    await ws.close();
  });

  it('renders the Welcome letter with its inputs', async () => {
    const { render, ws } = await openCopy();
    expect((await render.analyze(ID.welcome)).map((r) => r.id)).toEqual(['name', 'plan']);
    const res = await render.render(ID.welcome, { name: 'Ada', plan: 'Pro' });
    expect(res.status).toBe('completed');
    const year = new Date().getFullYear();
    expect(res.output).toBe(
      `# Welcome to Acme Corp, Ada!

Thanks for choosing the **Pro** plan.

Acme Corp helps you turn templates into documents, API calls and workflows.
Questions? Write to support@acme.example.

_Generated in ${year}._
`,
    );
    await ws.close();
  });

  it('resolves Get echo against the Public echo environment', async () => {
    const { templates, environments, apiRequest, ws } = await openCopy();
    const env = (await environments.list())[0]!;
    await environments.setSelection(env.id);
    const request = JSON.parse(
      (await templates.requireTemplate(ID.getEcho)).source,
    ) as HttpRequestModel;
    const out = await apiRequest.resolve(ID.getEcho, request, { name: 'Ada' });
    expect(out.request.url).toBe('https://httpbin.org/get?name=Ada');
    await ws.close();
  });
});
